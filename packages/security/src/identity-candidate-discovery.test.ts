import { getDb, schema } from "@web3-hunter/db";
import { createTestDatabase, type TestDatabase } from "@web3-hunter/db/testing";
import { describe, expect, it } from "vitest";
import {
  classifySecurityTargetIdentityCandidates,
  discoverSecurityTargetIdentityCandidates,
  type SecurityTargetIdentitySnapshot,
} from "./identity-candidate-discovery";
import { createSecurityTarget } from "./security-target-store";

function target(
  overrides: Partial<SecurityTargetIdentitySnapshot> & { slug: string },
): SecurityTargetIdentitySnapshot {
  return {
    id: overrides.id ?? overrides.slug,
    slug: overrides.slug,
    name: overrides.name ?? overrides.slug,
    repositoryUrl: overrides.repositoryUrl ?? null,
  };
}

function findCandidate(
  candidates: ReturnType<typeof classifySecurityTargetIdentityCandidates>,
  slugA: string,
  slugB: string,
) {
  return candidates.find(
    (candidate) =>
      (candidate.targetA.slug === slugA && candidate.targetB.slug === slugB) ||
      (candidate.targetA.slug === slugB && candidate.targetB.slug === slugA),
  );
}

describe("classifySecurityTargetIdentityCandidates (pure, fixture-only — no database required)", () => {
  it("1. classifies an exact, normalized full repository-path match across different slugs as high-confidence", () => {
    const candidates = classifySecurityTargetIdentityCandidates([
      target({ slug: "aave-llama", repositoryUrl: "https://github.com/aave/aave-v3-core" }),
      target({ slug: "aave-immunefi", repositoryUrl: "https://github.com/aave/aave-v3-core" }),
    ]);

    const candidate = findCandidate(candidates, "aave-llama", "aave-immunefi");
    expect(candidate?.classification).toBe("high-confidence");
    expect(candidate?.generatedByNameSimilarityHint).toBe(false);
  });

  it("2. classifies the same GitHub organization with different repositories as candidate-only, never high-confidence", () => {
    const candidates = classifySecurityTargetIdentityCandidates([
      target({ slug: "protocol-one", repositoryUrl: "https://github.com/some-dao/protocol-one" }),
      target({ slug: "protocol-two", repositoryUrl: "https://github.com/some-dao/protocol-two" }),
    ]);

    const candidate = findCandidate(candidates, "protocol-one", "protocol-two");
    expect(candidate?.classification).toBe("candidate-only");
    expect(candidate?.classification).not.toBe("high-confidence");
  });

  it("2b. classifies two organization-only URLs that are textually identical as candidate-only, not high-confidence (an org URL is never mistaken for a repository-path match)", () => {
    const candidates = classifySecurityTargetIdentityCandidates([
      target({ slug: "org-only-a", repositoryUrl: "https://github.com/some-dao" }),
      target({ slug: "org-only-b", repositoryUrl: "https://github.com/some-dao" }),
    ]);

    const candidate = findCandidate(candidates, "org-only-a", "org-only-b");
    expect(candidate?.classification).toBe("candidate-only");
  });

  it("3. classifies similar names with no independent identity evidence as insufficient-evidence (generated by the hint, never upgraded)", () => {
    const candidates = classifySecurityTargetIdentityCandidates([
      target({ slug: "stargate-finance", name: "Stargate Finance", repositoryUrl: null }),
      target({ slug: "stargatefinance", name: "StargateFinance", repositoryUrl: null }),
    ]);

    const candidate = findCandidate(candidates, "stargate-finance", "stargatefinance");
    expect(candidate?.classification).toBe("insufficient-evidence");
    expect(candidate?.generatedByNameSimilarityHint).toBe(true);
  });

  it("4. classifies similar names with conflicting repository URLs as conflict, not influenced by the name hint", () => {
    const candidates = classifySecurityTargetIdentityCandidates([
      target({
        slug: "stargate-finance",
        name: "Stargate Finance",
        repositoryUrl: "https://github.com/stargate-finance/stargate-v2",
      }),
      target({
        slug: "stargatefinance",
        name: "StargateFinance",
        repositoryUrl: "https://github.com/vechain/stargate-fork",
      }),
    ]);

    const candidate = findCandidate(candidates, "stargate-finance", "stargatefinance");
    expect(candidate?.classification).toBe("conflict");
    expect(candidate?.generatedByNameSimilarityHint).toBe(false);
  });

  it("5. treats missing repository URLs with no name/slug similarity as not worth generating at all", () => {
    const candidates = classifySecurityTargetIdentityCandidates([
      target({ slug: "alpha-protocol", name: "Alpha Protocol", repositoryUrl: null }),
      target({ slug: "zeta-markets", name: "Zeta Markets", repositoryUrl: null }),
    ]);

    expect(findCandidate(candidates, "alpha-protocol", "zeta-markets")).toBeUndefined();
  });

  it("5b. treats one-sided missing repository URL, with no similarity, as not worth generating", () => {
    const candidates = classifySecurityTargetIdentityCandidates([
      target({
        slug: "alpha-protocol",
        name: "Alpha Protocol",
        repositoryUrl: "https://github.com/alpha/alpha",
      }),
      target({ slug: "zeta-markets", name: "Zeta Markets", repositoryUrl: null }),
    ]);

    expect(findCandidate(candidates, "alpha-protocol", "zeta-markets")).toBeUndefined();
  });

  it("6. normalizes harmless URL formatting differences (case, trailing slash, .git suffix) to a high-confidence match", () => {
    const candidates = classifySecurityTargetIdentityCandidates([
      target({
        slug: "widget-llama",
        repositoryUrl: "https://github.com/Widget-Org/widget-core.git",
      }),
      target({
        slug: "widget-immunefi",
        repositoryUrl: "HTTPS://GITHUB.COM/widget-org/widget-core/",
      }),
    ]);

    const candidate = findCandidate(candidates, "widget-llama", "widget-immunefi");
    expect(candidate?.classification).toBe("high-confidence");
  });

  it("7. produces stable, deterministic output ordering regardless of input order", () => {
    const fixtures = [
      target({ slug: "zzz-target", repositoryUrl: "https://github.com/z-org/z-repo" }),
      target({ slug: "aaa-target", repositoryUrl: "https://github.com/z-org/z-repo-fork" }),
    ];

    const first = classifySecurityTargetIdentityCandidates(fixtures);
    const second = classifySecurityTargetIdentityCandidates([...fixtures].reverse());

    expect(first).toEqual(second);
    expect(first[0]?.targetA.slug).toBe("aaa-target");
    expect(first[0]?.targetB.slug).toBe("zzz-target");
  });

  it("8. reports multiple candidate pairs without duplicating any pair", () => {
    const candidates = classifySecurityTargetIdentityCandidates([
      target({ slug: "a-llama", repositoryUrl: "https://github.com/org-a/repo-a" }),
      target({ slug: "a-immunefi", repositoryUrl: "https://github.com/org-a/repo-a" }),
      target({ slug: "b-llama", repositoryUrl: "https://github.com/org-b/repo-b" }),
      target({ slug: "b-immunefi", repositoryUrl: "https://github.com/org-b/repo-b" }),
    ]);

    const highConfidencePairs = candidates.filter((c) => c.classification === "high-confidence");
    expect(highConfidencePairs).toHaveLength(2);

    const seen = new Set<string>();
    for (const candidate of candidates) {
      const key = [candidate.targetA.slug, candidate.targetB.slug].sort().join("::");
      expect(seen.has(key)).toBe(false);
      seen.add(key);
    }
  });

  it("never upgrades a hint-generated pair past insufficient-evidence, even with a very strong name match", () => {
    const candidates = classifySecurityTargetIdentityCandidates([
      target({ slug: "exact-same-name-a", name: "Identical Project Name", repositoryUrl: null }),
      target({ slug: "exact-same-name-b", name: "Identical Project Name", repositoryUrl: null }),
    ]);

    const candidate = findCandidate(candidates, "exact-same-name-a", "exact-same-name-b");
    expect(candidate?.classification).toBe("insufficient-evidence");
  });

  it("treats a GitHub-style URL against a non-GitHub URL as insufficient evidence (not directly comparable), never a conflict", () => {
    const candidates = classifySecurityTargetIdentityCandidates([
      target({ slug: "mixed-a", repositoryUrl: "https://github.com/some-org/some-repo" }),
      target({ slug: "mixed-b", repositoryUrl: "https://gitlab.com/some-org/some-repo" }),
    ]);

    const candidate = findCandidate(candidates, "mixed-a", "mixed-b");
    expect(candidate?.classification).toBe("insufficient-evidence");
  });

  it("never generates a same-slug pair (defensive — slug is a DB-level unique constraint, this input is already invalid)", () => {
    const candidates = classifySecurityTargetIdentityCandidates([
      target({ id: "id-1", slug: "same-slug", repositoryUrl: "https://github.com/org/one" }),
      target({ id: "id-2", slug: "same-slug", repositoryUrl: "https://github.com/org/two" }),
    ]);

    expect(candidates).toHaveLength(0);
  });
});

describe("discoverSecurityTargetIdentityCandidates (integration — proves the wrapper is read-only)", () => {
  it("9. never mutates any row it reads, verified by snapshotting actual table contents before and after", async () => {
    const testDb: TestDatabase = await createTestDatabase();
    process.env.DATABASE_URL = testDb.connectionString;

    try {
      await createSecurityTarget({
        slug: "readonly-check-a",
        name: "Readonly Check A",
        repositoryUrl: "https://github.com/readonly-org/repo-a",
      });
      await createSecurityTarget({
        slug: "readonly-check-b",
        name: "Readonly Check B",
        repositoryUrl: "https://github.com/readonly-org/repo-a",
      });

      const db = getDb();
      const before = await db.select().from(schema.securityTarget);
      const identityBefore = await db.select().from(schema.securityTargetSourceIdentity);

      const result = await discoverSecurityTargetIdentityCandidates();

      const after = await db.select().from(schema.securityTarget);
      const identityAfter = await db.select().from(schema.securityTargetSourceIdentity);

      // The actual table contents are byte-identical before and after —
      // this proves no row was inserted, updated, or deleted by the
      // call, from the database's own state rather than a source-code
      // search for mutation methods.
      expect(after).toEqual(before);
      expect(identityAfter).toEqual(identityBefore);

      expect(result.targetsInspected).toBe(2);
      expect(result.pairwiseComparisons).toBe(1);
      const candidate = findCandidate(result.candidates, "readonly-check-a", "readonly-check-b");
      expect(candidate?.classification).toBe("high-confidence");
    } finally {
      await testDb.stop();
    }
  }, 60_000);
});
